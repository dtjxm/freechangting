  /// 台名噪声清理（合并键与展示名共用）。
  ///
  /// 真实清单里**同一个台有多种写法**，不清理就会在列表里并排出现，
  /// 用户看到的就是「央视分类下同一套台被列了好几遍」：
  ///   `上虞新闻综合 (720p) [Not 24/7]` / `上虞新闻频道` / `上虞新商都` / `上虞新商都频道`
  /// 处理：括号注记 → 分辨率/编码标签 → 中文画质词。
  /// ⚠ 有意**不动 `4K` / `8K`** —— 它们是真实存在的独立频道（`CCTV4K` / `CCTV8K`），
  ///   抹掉会把 `CCTV4K` 变成 `CCTV`，与「CCTV」撞车。
  /// 括号里算得上「噪声」的内容（画质 / 编码 / 地域可用性注记）。
  static const String _noiseTok =
      r'(?:\d{3,4}[pi]|4k|8k|hd|sd|fhd|uhd|hevc|h\.?26[45]|avc|not\s*24/?7|geo-?blocked|高清|超清|标清|蓝光|原画|流畅|试看)';

  /// 括号内容**整体**都是噪声才算噪声（可逗号分隔多个）。
  static final RegExp _noiseInner =
      RegExp('^(?:$_noiseTok)(?:[\\s,，/]*(?:$_noiseTok))*\$', caseSensitive: false);

  static String _stripNoise(String s) {
    var t = s;
    // ⚠ 只清「内容确实是噪声」的括号 —— 早期实现把**所有**括号内容都删了，于是
    //   `NTV (Bangladesh)` / `TV4 (Poland)` / `NRK 1 (Agder)` / `ATV (Turkiye)`
    //   被并成同一个「NTV / TV4 / NRK1 / ATV」。一次 20 源仿真里，
    //   合并 ≥6 种写法的键有 71 个，其中大半是这种**跨国 / 跨地区误合并**。
    //   国家名、地区名、频道别称必须保留。
    t = t.replaceAllMapped(
        RegExp(r'[（(\[【]([^）)\]】]*)[）)\]】]'),
        (m) => _noiseInner.hasMatch(m.group(1)!.trim()) ? '' : m.group(0)!);
    t = t.replaceAll(RegExp(r'\b(1080P|1080I|720P|576I|576P|540P|480I|480P|360P|2160P|HEVC|H265|H264|AVC|UHD|FHD|50FPS|60FPS|25FPS)\b',
        caseSensitive: false), '');
    t = t.replaceAll(RegExp(r'高清|超清|标清|蓝光|原画'), '');
    // 尾部裸标清/赫兹数（如 `CCTV2 576`）—— 只吃**3 位**，避免误伤 4 位年份
    // （`春晚 2024` 这类要靠年份去做归一，不能被吃掉）。
    t = t.replaceAll(RegExp(r'\s\d{3}$'), '');
    return t;
  }

  /// **地区分版**标记 —— `CCTV4欧洲` / `CCTV4美洲` 是**不同的流**，
  /// 不能因为 [canon] 把 CCTV 后辍截掉就并成同一个「CCTV4」（实测踩过：
  /// 一次仿真里 CCTV4 被并进 25 个变体，其中含欧洲 / 美洲版）。
  static const List<String> _feedMarkers = [
    '欧洲', '美洲', '非洲', '大洋洲', '香港版', '澳门版', '台湾版', '日本版', '韩国版',
    'EUROPE', 'AMERICA', 'AFRICA', 'OCEANIA', 'AUSTRALIA',
  ];

  /// 跨源**去重键**：把同一台的不同写法归到同一个键。
  ///
  /// 三步：① 清噪声 + [canon] 归一 → ② 查别名表（`CCTV1综合` / `央视一套` → `CCTV1`）
  /// → ③ 去尾部通用词（`频道` / `电视台` / `台` / `综合`）。
  /// 例：`上虞新闻频道` 与 `上虞新闻综合` → 同为 `上虞新闻`，合并成一条（多线路）。
  ///
  /// ⚠ 有意**不去尾部「卫视」**：`北京卫视` 与 `北京` 是两个台，合并会出错。
  ///   代价是 `海南电视台` 与 `海南卫视` 不会合并（少见，可接受）。
  /// 春晚年份归一。
  /// 源里同一届春晚有两份清单、两种写法 —— `1987年春晚`（「春晚频道」组）
  /// 与 `春晚1987`（「历年春晚」组），实测 68 条其实只有 44 届。
  /// 只有当「除去春晚字样后剩下的就是一个 4 位年份」时才归一，
  /// 所以 `2026天津相声春晚`、`辽视组团上春晚的直播间` 不会被误并。
  static String? _chunwanYear(String s) {
    final t = s.replaceAll('春节联欢晚会', '春晚').replaceAll('春节晚会', '春晚');
    if (!t.contains('春晚')) return null;
    final rest = t.replaceAll('春晚', '').replaceAll(RegExp(r'[年\s\-—－·_]'), '');
    return RegExp(r'^\d{4}$').hasMatch(rest) ? rest : null;
  }

  static String mergeKey(String name) {
    final noisy = _stripNoise(name);
    final y = _chunwanYear(noisy);
    if (y != null) return 'CCTV春晚$y';                       // ① 春晚年份归一
    final up = noisy.replaceAll(RegExp(r'[\s\-—－·_]+'), '').toUpperCase();
    var c = canon(noisy);
    c = alias[c] ?? c;                                        // ② 别名归一
    c = c.replaceAll(RegExp(r'(电视台|频道|台)$'), '');        // ③ 尾部通用词
    c = c.replaceAll(RegExp(r'综合$'), '');
    c = alias[c] ?? c;
    // 地区分版另立一键
    for (final m in _feedMarkers) {
      if (up.contains(m) && !c.contains(m)) return '$c·$m';
    }
    return c;
  }

  /// **展示名**：别名表里有规范名就用它（`CCTV1` / `CGTN纪录`），否则保留原始写法。
  static String displayName(String raw) {
    final noisy = _stripNoise(raw);
    final y = _chunwanYear(noisy);
    if (y != null) return '$y年春晚';                          // 春晚统一显示为「1987年春晚」
    final c = canon(noisy);
    final base = alias[c] ?? raw.trim();
    // 地区分版（`CCTV4 欧洲` / `CCTV4 美洲` …）要**与合并键一致地**带上版别后缀 ——
    // 否则 4 个分版会并排显示成同一个「CCTV4」，看起来像重复行（实测踩过）。
    final up = noisy.replaceAll(RegExp(r'[\s\-—－·_]+'), '').toUpperCase();
    for (final m in _feedMarkers) {
      if (up.contains(m) && !base.contains(m)) return '$base·$m';
    }
    return base;
  }

