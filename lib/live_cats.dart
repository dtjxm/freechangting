  /// 画质后缀（台名末尾）—— 归一时剥掉。
  /// v2.2.4（10-14 第 5 批）：**`江苏卫视HD` 因多这一个 HD 而匹配不到别名表** ——
  ///   别名表的 key 是 `江苏卫视`。落空后一路走到 ⑧ 的分组兜底：
  ///   在「央视频」分组里被判成「央视」（用户反馈的「央视里混进各地卫视」就是这条），
  ///   分组为空时则被判成「地方」。剥掉后缀两边都归位。
  /// ⚠ 用 lookbehind 要求前一个字符是**汉字或数字**：只剥 `江苏卫视HD` 这种，
  ///   不碰 `ESD` 这类以字母结尾的正常台名（否则会被削成 `E`）。
  /// ⚠ 有意**不剥 `4K` / `8K`**：`CCTV4K` / `CCTV8K` 是真实存在的独立超高清频道，
  ///   剥掉会变成 `CCTV`，与「CCTV」撞车。
  static final RegExp _qualityTail =
      RegExp(r'(?<=[\u4e00-\u9fff0-9])(?:HD|SD|FHD|UHD)$');

  /// 台名归一：去空格/连字符/间隔号 → 繁转简 → 大写 → 剥画质后缀 → CCTV 归一（含前导零）。
  /// `CCTV-02`→`CCTV2`、`CCTV7军事`→`CCTV7`、`CCTV5G`→`CCTV5`、`CCTV5+G`→`CCTV5+`；
  /// `江苏卫视HD`→`江苏卫视`；豁免 `CCTV4K` / `CCTV8K`。
  static String canon(String name) {
    var s = toSimp(name.replaceAll(RegExp(r'[\s\-—－·_]+'), ''));
    s = s.toUpperCase();
    s = s.replaceFirst(_qualityTail, '');
    if (_cctvPrefix.hasMatch(s)) {
      final m = _cctvNum.firstMatch(s);
      if (m != null) {
        final n = int.tryParse(m.group(1) ?? '') ?? 0;
        s = 'CCTV$n${m.group(2) ?? ''}';
      }
    }
    return s;
  }

  /// 繁体 → 简体（精简表）—— 港澳台与南方地方台名大量用繁体，
  /// 不转换会让省市关键词、地区关键词全部匹配不上。
  static String toSimp(String s) {
    if (s.isEmpty) return s;
    var hit = false;
    for (final r in s.runes) {
      if (hanziT2S.containsKey(String.fromCharCode(r))) { hit = true; break; }
    }
    if (!hit) return s;
    final sb = StringBuffer();
    for (final r in s.runes) {
      final c = String.fromCharCode(r);
      sb.write(hanziT2S[c] ?? c);
    }
    return sb.toString();
  }

  /// 去分隔符（`·•・|｜/` 与空白）—— 兼容「🌊港·澳·台」这类被分隔符切碎的港澳台分组名。
  static String _desep(String s) =>
