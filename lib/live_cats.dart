  /// 分组名 + 频道名 + tvg-id → 一级分类。
  /// 返回 [radioCat] 表示广播（调用方应整批丢弃）。
  ///
  /// ⚠ 本方法的判定顺序**必须与离线脚本 merge_classify.py 的 `cat_of` 严格一致**，
  ///   否则两端会给出不同分类（离线实测踩过：`Ace TV` 被判成央视、`国际频道` 被判成地方）。
  ///   差异只在两处，且是刻意的：
  ///     ① 离线返回 `其他` / `影视` / `历年春晚` 的地方 → 这里返回 [vodCat]
  ///        （方案 v2 已把这些并进「影视点播」，细分交给 [vodSub]）；
  ///     ② 离线靠「来源专列是国际 + 名称无中文 → 国际」在 main 里做后处理，
  ///        这里没有来源信息，改为「名称无中文 → 国际」（放在「频道 → 地方」之前，
  ///        否则「🚀国际频道」会被下一条判成地方）。
  static String catOf(String group, String name, String tvgId) {
    final c = canon(name);
    final up = c.toUpperCase();
    /// 分组名大写形式（⑤ / ⑥′ / ⑨′ 都要用，只算一次）
    final gup = group.toUpperCase();
    /// 分组是不是「直播平台的点播 / 轮播专区」—— 见 ⑨′
    final isPlat = _platformGroup.hasMatch(_desep(gup));

    // ⓪ 人工判定表 —— **优先级最高**（比别名表还高）。
    //    影视点播里混着的「真电视台」（央视付费频道 / 地方台专业频道）在这里定案；
    //    否则「怀旧剧场」「都市剧场」「京视剧场」会被名称规则里的「剧场」抢进「影视点播」。
    final mcat = manualCat[c];
    if (mcat != null) return mcat;

    // ① 急救科普 / 相声 / 小品 —— 必须最先拦下：
    //    这些名字含「儿童」「健康」「音乐」等，不拦会被少儿动画 / 音乐戏曲按名抢走，
    //    或按源站分组（「🎸音乐专区」「🎬影视频道」）抢走。
    for (final k in firstaidKw) {
      if (up.contains(k)) return vodCat;
    }
    if (up.contains('相声') || up.contains('小品') || up.contains('德云社')) return vodCat;

    // ② 台名精确别名（CCTV1 / 央视一套 / CCTV1综合 → 同一台）
    final al = alias[c];
    if (al != null) {
      return (al.startsWith('CCTV') || al.startsWith('CGTN') || al.startsWith('中国教育'))
          ? '央视'
          : '卫视';
    }

    // ③ 央视系前缀 —— `CCTV电视指南`、`CETV-2教育教学`、`CEC健康` 这类
    //    既不在别名表里、又没有中文内容类型词的频道由此兜住。
    if (_brandPrefix.hasMatch(up)) return '央视';

    // ④ 广播 —— 本软件已移除（记录另存《广播频道清单》），调用方整批丢弃。
    //    放在前缀之后：避免误伤「中央广播电视总台」这类含「广播」的央视台名。
    if (group.contains('收音广播') || group.contains('广播')) return radioCat;
    if (RegExp(r'FM\s*\d|调频|广播电台|电台$').hasMatch(c)) return radioCat;

    // ⑤ 分组名规则（分组名比频道名可靠，且能救回被类型词抢走的频道 ——
    //    「🎎动漫直播」里的「网球王子」「黑子的篮球」本来会被判成体育）
    //    v2.2.4（10-14 追加）：改为**大小写不敏感** —— 源里 `yy电视剧` / `YY轮播`
    //    两种写法都有，大小写敏感匹配会漏掉一半。
    for (final r in groupRules) {
      for (final kw in r.skip(1)) {
        if (gup.contains(kw.toUpperCase())) return r[0];
      }
    }

    // ⑥ 频道名规则（中文子串 / 英文左边界）
    var byName = '';
    for (final r in nameRules) {
      for (final kw in r.skip(1)) {
        if (kwHit(kw, up)) { byName = r[0]; break; }
      }
      if (byName.isNotEmpty) break;
    }
    // ⑥′ 例外：**按频道名判成了影视点播、但分组是省级 / 地方标记**的其实是地方台。
    //     用户反馈「影视点播页的电影 / 电视剧 / 综艺 / 其他里还混着电视台」正是这一类：
    //       「江苏频道」里的「句容影院频道」、「☘️上海频道」里的「东方影视」。
    //     只对影视点播生效 —— 否则「浙江音乐」「浙江少儿」这类真·专业频道
    //     也会被省级分组拉进「地方」。
    if (byName == vodCat && _groupProv(group, c).isNotEmpty) return '地方';
    // ⑥′ 例外二：平台专区里的「XX频道」会被 ⑥ 末尾那条兜底词（`频道` → 地方）
    //     误判成地方台 —— 实测「虎牙轮播」组里 127 条如此。清掉后交给 ⑨′ 处理。
    if (isPlat && byName == '地方') byName = '';
    if (byName.isNotEmpty) return byName;

    // ⑦ 名字里完全没有「类型词」且很短 + 分组是地方/纪录标记 → 地方台
    //   （iptv2025 的「纪录频道」组里混了一批吉林/黑龙江县级台，
    //     只看分组会把它们误判成纪录片）
    //   走到这里说明 ⑥ 未命中，即 has_genre == false。
    if (c.length <= 6 &&
        (group.contains('地方频道') || group.contains('☘️') || group.contains('纪录'))) {
      return '地方';
    }

    // ⑦′ v2.2.4（10-14 第 5 批）：**台名明确写着「XX卫视」的，以台名为准**。
    //   「央视频」这类分组里混着各省卫视的上星信号，只看分组会被整批归进央视
    //   （用户反馈「央视分类内部混入各地卫视了」）。覆盖别名表够不到的写法
    //   （`山东卫视4K` / `湖南卫视国际` 这类）。
    //   ⚠ 位置在 ⑦ 之后是有意的：港澳台系的 `凤凰卫视` / `星空卫视` 在 ⓪ 与 ⑥ 就已定案，
    //     走不到这里；`c.length <= 8` 是防止超长名（`XX卫视购物频道`）被误收。
    if (c.length <= 8 && RegExp(r'卫视(?:HD|SD|4K|8K)?$').hasMatch(c)) return '卫视';

    // ⑧ 分组名兜底。这两条必须**先于**下面的「频道」判定 ——
    //    否则「🎦影视频道」会被当成地方台。
    if (group.contains('直播中国') || group.contains('景区直播')) return '风景慢直播';
    if (RegExp(r'(家庭影院|轮播剧场|电视剧场|电影轮播|放映厅|影院|影视频道)').hasMatch(group)) {
      return vodCat;
    }
    if (group.contains('春晚')) return vodCat;
    if (group.contains('卫视')) return '卫视';
    // 港澳台的地域标记（去分隔符后匹配，兼容「🌊港·澳·台」这种写法）
    if (RegExp(r'(港澳|港台|香港|澳门|台湾)').hasMatch(_desep(group))) return '港澳台';
    // 省级 /「☘️XX频道 / 地方频道」是**强地方标记**，优先于「纪录 / 电影」等泛频道名
    if (_groupProv(group, c).isNotEmpty) return '地方';
    // ⑦″ v2.2.4（10-14 第 6 批）：**分组认不出、但台名带省级行政区 / 城市名的，也是地方台**。
    //   实测「央视频」分组里混着「重庆新农村」「重庆社会与法」—— 该分组含「央视」，
    //   原先被整批归进央视（用户 10-14 第二次截图）。必须排在下面的「央视」判定之前。
    if (_nameProv(c).isNotEmpty) return '地方';
    // v2.2.4（10-14 第 6 批）：**不再用裸 `contains('央视')`**。
    //   「央视频」是央视的 App 名，但这个分组是**混装**的 —— 实测里面塞着邵氏电影轮播、
    //   重庆地方台。只有「央视频道 / 央视台 / 央视付费」这类明确分组才整组归央视；
    //   「央视频」里的真·央视台（CCTV 系列）靠 ② 别名表与 ③ 品牌前缀早就判定了，不受影响。
    if (group.contains('央视频道') ||
        group.contains('央视台') ||
        group.contains('央视付费')) {
      return '央视';
    }
    if (group.contains('纪录')) return '纪录片';
    if (RegExp(r'(电影|影视)').hasMatch(group)) return vodCat;
    if (group.contains('体育')) return '体育';
    if (RegExp(r'(动画|儿童|卡通|动漫)').hasMatch(group)) return '少儿动画';
    if (group.contains('音乐') || group.contains('演唱')) return '音乐戏曲';

    // ⑨ 外文名 → 国际。
    //    ⚠ 必须在⑩之前：否则「🚀国际频道」里含「频道」二字，会被判成地方台
    //    （离线方案靠「来源专列=国际」后处理纠正，这里没有来源信息，只能靠名称）。
    if (!_cjk.hasMatch(c)) return '国际';

    // ⑨′ 直播平台的点播 / 轮播专区兜底（虎牙 / 斗鱼 / 抖音 / 芒果 / 咪咕 / YY …）。
    //     放在这里 —— **各条名称规则之后、地方兜底之前** —— 是故意的：
    //     这些分组是「混装」的（动漫 / 电影 / 体育 / 音乐都有），
    //     频道名判得出的必须按名字判（「虎牙轮播」里的「体育频道」要进体育）；
    //     只有名字完全判不出类型时，才落进影视点播。实测 1,500+ 条如此，
    //     原先整批掉进「地方 · 其他」。
    //     ⚠ 不写裸 `YY` —— `HAPPY KIDS` 这类分组也会被误命中。
    if (isPlat) return vodCat;

    // ⑩ 「XX频道」兜底 → 地方
    if (group.contains('频道')) return '地方';

    // ⑪ 含「综合 / 电视台 / X套」→ 地方
    if (RegExp(r'(综合|电视台|一套|二套|三套|四套|五套)$').hasMatch(c)) return '地方';

    // ⑫ 短名（≤6 字）且看不出类型 → 基本是地方台
    if (c.length <= 6 && !RegExp(r'[省市县区镇]').hasMatch(c)) return '地方';

    return vodCat; // 剩下的多是点播式内容
  }

