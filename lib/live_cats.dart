  /// 5 大类顺序（2.2.3 形态）
  static const List<String> fiveOrder = [
    '央视频道', '卫视频道', '港澳台·国际', '地方频道', '国际·其他',
  ];

  /// 一级分类（2.2.3 形态）—— 按分组名 + 频道名判定，返回 5 大类之一、
  /// [radioCat]（广播，丢弃）或 [dropCat]（轮播频道，丢弃）。
  ///
  /// 判定顺序：
  ///   ① 广播 → [radioCat]
  ///   ② 台名含「春晚」→ 央视频道（历年春晚保留）
  ///   ③ 复用 [catOf] 判定是否为「影视点播」轮播内容 → 是则 [dropCat] 丢弃
  ///      （[catOf] 已做大量纠偏：央视付费频道/地方专业频道等真电视台不会被误判）
  ///   ④ 其余按 2.2.3 的分组名判定 5 大类
  static String catOfV223(String group, String name, String tvgId) {
    final c = canon(name);
    final up = c.toUpperCase();
    // ① 广播 → 丢弃
    if (group.contains('收音广播') || group.contains('广播')) return radioCat;
    if (RegExp(r'FM\s*\d|调频|广播电台|电台$').hasMatch(c)) return radioCat;
    // ② 历年春晚 → 央视频道（保留）
    if (_chunwanYear(c) != null || up.contains('春晚')) return '央视频道';
    // ③ 影视点播轮播内容 → 丢弃（复用 catOf 的精确判定）
    if (catOf(group, name, tvgId) == vodCat) return dropCat;
    // ④ 2.2.3 的分组名判定 5 大类
    final g = group.replaceAll(RegExp(r'[^一-龥A-Za-z0-9]'), '');
    final u = g.toUpperCase();
    if (u.contains('CCTV') || g.contains('央视') || g.contains('CGTN') || g.contains('CETV')) {
      return '央视频道';
    }
    if (g.contains('卫视')) return '卫视频道';
    if (RegExp(r'港澳|港台|台湾|凤凰|国际|海外').hasMatch(g)) return '港澳台·国际';
    if (!RegExp(r'[一-龥]').hasMatch(g)) return '国际·其他';
    if (g.startsWith('其他')) return '国际·其他';
    return '地方频道';
  }

