    final raw = tvgId.split('@').first;
    final i = raw.lastIndexOf('.');
    if (i < 0 || i >= raw.length - 1) return intlUnknown;
    return ccZh[raw.substring(i + 1).toLowerCase()] ?? intlUnknown;
  }

