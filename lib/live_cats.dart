  static bool isFallbackSub(String sub) => sub == '其他' || sub == intlUnknown;

  /// 关键词命中。**纯 ASCII 关键词加左边界** —— 否则 `ACETV` 会命中 `CETV`、
  /// `TVSPINBALL` 会命中 `NBA`（离线实测踩过，央视一度虚增到 61 个）。
  /// 只加左边界：右边界会误伤 `HOY TV`→`HOYTV`、`TVB1` 这类正常写法。
  static bool kwHit(String kw, String up) {
    final k = kw.toUpperCase();
    if (_asciiKw.hasMatch(k)) {
      var i = up.indexOf(k);
      while (i >= 0) {
        final okLeft = i == 0 || !_alpha.hasMatch(up[i - 1]);
        if (okLeft) return true;
        i = up.indexOf(k, i + 1);
      }
      return false;
    }
    return up.contains(k);
  }

  /// 从 tvg-id 取国家中文名。形如 `CNN.us@SD` / `NHK.jp@SD` → 美国 / 日本。
  static String countryOf(String tvgId) {
