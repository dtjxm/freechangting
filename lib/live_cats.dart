  /// 频道在列表里的排序键（字符串比较，越小的越靠前）。
  ///
  /// 解决的问题（用户 2026-10-14：「电视台的排序能否连贯，例如 CCTV6 跑到下边了」）：
  /// 列表原先是**源清单顺序**，而 20 份清单各自把 CCTV 系列打散，
  /// 于是 CCTV1 / CCTV10 / CCTV13 / CCTV6 … 排得毫无规律。
  /// 这里按「品牌 → 频道号 → 名称」给一个稳定键，让同一频道号的台连在一起。
  ///
  /// 说明：只用于**列表展示顺序**，与分类判定、去重无关。
  static String sortKey(String cat, String sub, String name) {
    final d = displayName(name);
    final c = canon(_stripNoise(name));
    switch (cat) {
      case '央视频道':
        // 4K / 8K **先判并整段排到数字频道之后** —— 否则 `CCTV4K超高清` 会被下面的
        // 数字正则当成「CCTV4」，与真正的 CCTV4 交错在一起（实测踩过）。
        if (c.startsWith('CCTV4K') || c.startsWith('CCTV8K')) return '19$c';
        final m = RegExp(r'^CCTV0*(\d{1,2})(\+)?').firstMatch(c);
        if (m != null) {
          final n = int.parse(m.group(1)!);
          return '1${n.toString().padLeft(2, '0')}${m.group(2) == '+' ? 1 : 0}';
        }
        if (c.startsWith('CCTV')) return '18$c';
        if (c.startsWith('CGTN')) return '2$c';
        if (c.startsWith('CETV') || c.contains('中国教育')) return '3$c';
        return '4$c';
      case '卫视频道':
        // 非中文台名垫底（源里有个 `CNN` 因分组名含「卫视」被判进本类，不该占头条）
        return '${hasCjk(d) ? '0' : '9'}$d';
      case '地方频道':
        final p = provinces.indexOf(sub);
        return '${(p < 0 ? 99 : p).toString().padLeft(2, '0')}$d';
      case '港澳台·国际':
        final r = hmtOrder.indexOf(sub);
        return '${r < 0 ? 9 : r}$d';
      default:
        return d;
    }
  }
