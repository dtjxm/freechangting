  /// 二级分类名。地方频道=省份、港澳台·国际=地区；其余大类返回空串（页面上不显示二级 chips）。
  /// v2.2.7：适配 2.2.3 五分类的大类名。
  static String subOf(String cat, String group, String name, String tvgId) {
    switch (cat) {
      case '地方频道':
        return provOf(group, canon(name));
      case '港澳台·国际':
        return hmtSub(group, canon(name));
      default:
        return '';
    }
  }

  /// **只看分组**里的省 / 市归属（不查频道名，无递归）—— 用于识别「这个分组是某省的频道包」。
  ///
  /// ⚠ 刻意不拿频道名本身去匹配省份：「上海正午2上海骑士」是片名不是上海台。
  /// 返回省名；不是地方分组则返回空串。
  static String _groupProvRaw(String group) {
    if (group.isEmpty) return '';
    // ① 分组名本身就是「XX频道」且 XX 是省级行政区（「江苏频道」「🏯北京频道」）
    final m = _provGroup.firstMatch(group);
    if (m != null && provinces.contains(m.group(1))) return m.group(1)!;
    // ② 分组名带省级行政区 + 地方标记
    //   （「甘肃综合」「☘️浙江频道」「黑龙江综合」「山东移动」「☘️四川广电」）
    if (RegExp(r'(频道|☘️|地方|综合|移动|广电|网络)').hasMatch(group)) {
      for (final p in provinces) {
        if (group.contains(p)) return p;
      }
    }
    return '';
  }

  /// 分组的省归属；分组自己认不出时，用频道名里的省 / 市兜底（仅在已是地方标记时）
  static String _groupProv(String group, String canonName) {
    final raw = _groupProvRaw(group);
    if (raw.isNotEmpty) return raw;
    if (group.contains('地方频道') || group.contains('☘️')) {
      return provOf(group, canonName);
    }
    return '';
  }

  /// **只看台名**的省 / 市归属（不看分组）。命中返回省名，没命中返回空串。
  ///
  /// v2.2.4（10-14 第 6 批）：给 [catOf] 的 ⑦″ 用 —— 揪出「央视频」这类**混装分组**下
  /// 夹带的地方台（实测「重庆新农村」「重庆社会与法」被整组当成央视）。
  /// ⚠ 与 [provOf] 的区别：provOf 认不出时返回「其他」，无法区分「认不出」与「没命中」；
  ///   本方法认不出就返回空串，调用方据此判断「台名里到底有没有地名」。
  /// ⚠ 只认**长度 ≥ 2** 的词：`city2prov` 里若有单字键（如「和」「阳」），
  ///   拿它去 contains 会大面积误伤（「和平」「阳江」…），宁可不认。
  static String _nameProv(String canonName) {
    for (final p in provinces) {
      if (canonName.contains(p)) return p;
    }
    for (final e in city2prov.entries) {
      if (e.key.length >= 2 && canonName.contains(e.key)) return e.value;
    }
    return '';
  }

  /// 地方 → 省份
  static String provOf(String group, String canonName) {
    final mp = manualProv[canonName];
    if (mp != null) return mp;
    // v2.2.4（10-14 追加）：分组自己认得出省就直接用 —— 实测「黑龙江综合」
    //   「山东移动」「☘️四川广电」这类分组的频道名里根本没有省名，
    //   只看频道名会让它们整批落进「地方·其他」（一次仿真里堆了 3,318 个）。
    final gp = _groupProvRaw(group);
    if (gp.isNotEmpty) return gp;
    for (final p in provinces) {
      if (canonName.contains(p)) return p;
    }
    for (final e in city2prov.entries) {
      if (canonName.contains(e.key)) return e.value;
    }
    return '其他';
  }

  /// 港澳台 → 地区
  static String hmtSub(String group, String canonName) {
    final hay = '$canonName $group'.toUpperCase();
    for (final r in hmtRules) {
      for (final kw in r.skip(1)) {
        if (hay.contains(kw.toUpperCase())) return r[0];
      }
    }
    return '其他华语';
  }

  /// 影视点播 → 内部子分类。
  /// **相声/小品/历年春晚先按名称判**，其余分组优先 ——
  /// 源站把相声段子塞进了「💃春晚小品」分组，只按分组判会让相声恒为 0（离线实测）。
  static String vodSub(String group, String canonName) {
    final hay = canonName.toUpperCase();
    for (final sub in vodNameFirst) {
      for (final r in vodRules) {
        if (r[0] != sub) continue;
        for (final kw in r.skip(1)) {
          if (hay.contains(kw.toUpperCase())) return sub;
        }
      }
    }
    for (final r in vodGroupRules) {
      for (final kw in r.skip(1)) {
        if (group.contains(kw)) return r[0];
      }
    }
    for (final r in vodRules) {
      for (final kw in r.skip(1)) {
        if (hay.contains(kw.toUpperCase())) return r[0];
      }
    }
    return '其他';
  }

