class AboutPage extends StatefulWidget {
  const AboutPage({super.key});

  @override
  State<AboutPage> createState() => _AboutPageState();
}

class _AboutPageState extends State<AboutPage> {
  bool _checking = false;

  Future<void> _checkUpdate() async {
    if (_checking) return;
    setState(() => _checking = true);
    final (state, info) = await UpdateService.instance.check();
    if (!mounted) return;
    setState(() => _checking = false);
    switch (state) {
      case CheckResult.available:
        showModalBottomSheet<void>(
          context: context,
          backgroundColor: context.subBg,
          isScrollControlled: true,
          shape: const RoundedRectangleBorder(
              borderRadius: BorderRadius.vertical(top: Radius.circular(16))),
          builder: (ctx) => UpdateSheet(info: info!),
        );
        break;
      case CheckResult.latest:
        ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('已是最新版本 $kAppVersion')));
        break;
      case CheckResult.skipped:
      case CheckResult.error:
        ScaffoldMessenger.of(context).showSnackBar(
            const SnackBar(content: Text('检查更新失败，请检查网络')));
        break;
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('关于电影世界')),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(14, 12, 14, 30),
        children: [
          // ---- 头部（v1.5.0 缩小）：LOGO + 应用名 + 版本，宽度收窄 ----
          Padding(
            padding: const EdgeInsets.symmetric(horizontal: 56),
            child: Column(
              children: [
                ClipRRect(
                  borderRadius: BorderRadius.circular(13),
                  child: Image.asset('assets/icon.png',
                      width: 52, height: 52, fit: BoxFit.cover),
                ),
                const SizedBox(height: 9),
                Text('电影世界',
                    style: TextStyle(
                        fontSize: 16.5,
                        fontWeight: FontWeight.bold,
                        color: context.tMain)),
                const SizedBox(height: 4),
                Text('${_versions.first.v} ｜ Android ｜ 片源 ${MacApi.instance.sources.length} 个',
                    style: TextStyle(fontSize: 11.5, color: context.tSub)),
              ],
            ),
          ),
          const SizedBox(height: 20),
          // ---- 三个区域入口（点击进入三级页面） ----
          Container(
            decoration: BoxDecoration(
              color: context.card,
              borderRadius: BorderRadius.circular(14),
            ),
            child: Column(children: [
              _entry(context, Icons.description_outlined, '软件说明',
                  sub: '功能介绍与产品定位',
                  color: const Color(0xFF6B8AF0),
                  onTap: () => _go(context, const _SoftwareIntroPage())),
              _divider(context),
              _entry(context, Icons.gavel_outlined, '免责声明',
                  sub: '使用条款与版权说明',
                  color: const Color(0xFFE05A6D),
                  onTap: () => _go(context, const _DisclaimerPage())),
              _divider(context),
              _entry(context, Icons.history_edu_outlined, '版本信息',
                  sub: '${_versions.first.v} · 全部版本更新记录',
                  color: const Color(0xFF4CBFA6),
                  onTap: () => _go(context, const _VersionInfoPage())),
              _divider(context),
              // v2.2.6：检查更新入口移到「关于」页（此前在「版本信息」三级页）
              _entry(context, Icons.system_update_alt, '检查更新',
                  sub: _checking ? '正在检查…' : '当前 ${_versions.first.v} · 联网检查新版本',
                  color: const Color(0xFFF0A05A),
                  onTap: _checking ? null : () => _checkUpdate()),
            ]),
          ),
          const SizedBox(height: 20),
          // v1.5.4：作者信息两行样式（参考音乐类 App 出品页脚）
          Text.rich(
            TextSpan(
              children: [
                TextSpan(
                    text: '靳小明',
                    style: TextStyle(
                        fontSize: 12.5,
                        fontWeight: FontWeight.bold,
                        color: context.tSub)),
                TextSpan(
                    text: ' · 出品 ｜ 2026年9月 于北京 制作',
                    style: TextStyle(
                        fontSize: 12.5, color: context.tFaint)),
              ],
            ),
            textAlign: TextAlign.center,
          ),
          const SizedBox(height: 5),
          Text('电影世界 · 个人自用版 · 感谢使用 🍊',
              textAlign: TextAlign.center,
              style: TextStyle(fontSize: 11.5, color: context.tFaint)),
        ],
      ),
    );
  }

  void _go(BuildContext context, Widget page) {
    Navigator.of(context).push(MaterialPageRoute(builder: (_) => page));
  }

  Widget _entry(BuildContext context, IconData icon, String title,
      {String? sub, required Color color, VoidCallback? onTap}) {
    return ListTile(
      onTap: onTap,
      contentPadding: const EdgeInsets.symmetric(horizontal: 14, vertical: 6),
      leading: Container(
        width: 40,
        height: 40,
        decoration: BoxDecoration(
          color: color.withValues(alpha: 0.14),
          borderRadius: BorderRadius.circular(11),
        ),
        child: Icon(icon, size: 21, color: color),
      ),
      title: Text(title,
          style: TextStyle(
              fontSize: 15, fontWeight: FontWeight.w600, color: context.tMain)),
      subtitle: sub == null
          ? null
          : Text(sub,
              style: TextStyle(fontSize: 11.5, color: context.tFaint)),
      trailing:
          Icon(Icons.chevron_right, size: 22, color: context.tFaint),
    );
  }

  Widget _divider(BuildContext context) => Padding(
        padding: const EdgeInsets.symmetric(horizontal: 14),
        child: Divider(height: 1, color: context.divider),
      );
}

