        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Container(
                padding:
                    const EdgeInsets.symmetric(horizontal: 8, vertical: 2),
                decoration: BoxDecoration(
                  color: current ? context.brand : context.chipBg,
                  borderRadius: BorderRadius.circular(6),
                ),
                child: Text(current ? '${v.v} · 当前' : v.v,
                    style: TextStyle(
                        fontSize: 11.5,
                        fontWeight: FontWeight.bold,
                        color: current ? Colors.white : context.tSub)),
              ),
              const SizedBox(width: 8),
              Text(v.date,
                  style: TextStyle(fontSize: 11.5, color: context.tFaint)),
            ],
          ),
          const SizedBox(height: 5),
          Text(v.note,
              style: TextStyle(
                  fontSize: 12.5, height: 1.6, color: context.tSub)),
        ],
      ),
    );
  }
}

